def render(receivers: List[Receiver]) -> str:
    lines = [HEADER]
    for receiver in receivers:
        bands = "[" + ",".join(
            "(%r,%r,%r)" % (band.name, round(band.center_khz, 6),
                            round(band.samplerate_khz, 6))
            for band in receiver.bands) + "]"
        tags = "[" + ",".join("%r" % tag for tag in receiver.satellite_bands) + "]"
        lines.append("_add(%r, %r, %r, %r, %s, %s)\n"
                     % (receiver.url, receiver.kind, receiver.latitude,
                        receiver.longitude, bands, tags))
    lines.append(FOOTER)
    return "".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default="sdrstream/catalogue.py",
                        help="where to write the module (default: %(default)s)")
    parser.add_argument("--timeout", type=float, default=30.0,
                        help="request timeout in seconds (default: 30)")
    parser.add_argument("--list-url", default=LIST_URL,
                        help="server list endpoint (default: the WebSDR list)")
    args = parser.parse_args(argv)

    receivers = gather(list_url=args.list_url, timeout=args.timeout)
    if not receivers:
        print("no receivers found; refusing to overwrite the catalogue",
              file=sys.stderr)
        return 1
    with open(args.out, "w") as handle:
        handle.write(render(receivers))
    print("wrote %s with %d receivers" % (args.out, len(receivers)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
