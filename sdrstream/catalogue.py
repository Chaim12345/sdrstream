"""Catalogue of public SDR receivers that can hear amateur satellites.

Generated by ``tools/build_catalogue.py`` from the WebSDR project's server list,
keeping the receivers whose published tuning ranges overlap the amateur 6 m,
2 m, 70 cm or 23 cm bands. Coordinates come from the server list and are only
good to a few kilometres: fine for deciding whether a satellite pass is
plausible, not for pointing a dish.

A receiver hears a satellite only while the satellite is above its local
horizon, and the useful window is shorter than that, so check the pass geometry
with :mod:`sdrstream.tracking` before trusting a recording.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, List, Optional, Tuple


@dataclass(frozen=True)
class Band:
    """A tuning range a receiver offers."""

    name: str
    center_khz: float
    samplerate_khz: float

    @property
    def low_hz(self) -> float:
        return (self.center_khz - self.samplerate_khz / 2) * 1000.0

    @property
    def high_hz(self) -> float:
        return (self.center_khz + self.samplerate_khz / 2) * 1000.0

    def covers(self, frequency_hz: float) -> bool:
        return self.low_hz <= frequency_hz <= self.high_hz


@dataclass(frozen=True)
class Receiver:
    """One public receiver and the bands it publishes."""

    url: str
    kind: str
    latitude: float
    longitude: float
    bands: Tuple[Band, ...] = ()
    satellite_bands: Tuple[str, ...] = ()

    @property
    def location(self) -> Tuple[float, float]:
        return self.latitude, self.longitude

    def can_hear(self, frequency_hz: float) -> bool:
        """Whether any published band covers *frequency_hz*."""
        return any(band.covers(frequency_hz) for band in self.bands)

    def band_for(self, frequency_hz: float) -> Optional[Band]:
        for band in self.bands:
            if band.covers(frequency_hz):
                return band
        return None


