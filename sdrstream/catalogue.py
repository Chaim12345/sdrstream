def for_frequency(frequency_hz: float, band: Optional[str] = None) -> List[Receiver]:
    """Receivers whose published bands cover *frequency_hz*.

    *band* optionally restricts the result to receivers tagged for one of
    ``"6m"``, ``"2m"``, ``"70cm"`` or ``"23cm"``.
    """
    out = [r for r in RECEIVERS.values() if r.can_hear(frequency_hz)]
    if band is not None:
        out = [r for r in out if band in r.satellite_bands]
    return sorted(out, key=lambda r: r.url)


def for_band(band: str) -> List[Receiver]:
    """Receivers tagged as covering *band*."""
    return sorted((r for r in RECEIVERS.values() if band in r.satellite_bands),
                  key=lambda r: r.url)


def nearest(latitude: float, longitude: float, frequency_hz: float,
            limit: int = 10) -> List[Receiver]:
    """Receivers that can hear *frequency_hz*, nearest to a position first."""
    import math

    def distance(r: Receiver) -> float:
        # Equirectangular approximation; adequate at this scale.
        dlat = math.radians(r.latitude - latitude)
        dlon = math.radians(r.longitude - longitude)
        x = dlon * math.cos(math.radians((r.latitude + latitude) / 2))
        return math.hypot(dlat, x)

    candidates = [r for r in RECEIVERS.values() if r.can_hear(frequency_hz)]
    return sorted(candidates, key=distance)[:limit]
